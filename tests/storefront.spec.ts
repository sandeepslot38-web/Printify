import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
})

test('catalogue, product sizing, bag persistence and coupon work', async ({ page }) => {
  await expect(page.getByRole('heading', { name: 'Made for the in-between.' })).toBeVisible()
  await page.getByRole('button', { name: 'Shop the new drop' }).click()
  await page.getByRole('button', { name: 'Heavyweight Box Tee' }).click()
  await expect(page.getByRole('heading', { name: 'Heavyweight Box Tee' })).toBeVisible()
  await page.locator('.sizes').getByRole('button', { name: 'M' }).click()
  await page.getByRole('button', { name: /Add to bag/ }).click()
  await page.getByRole('button', { name: 'Shopping bag' }).click()
  await page.getByRole('button', { name: 'View bag & checkout' }).click()
  await expect(page.getByText('Heavyweight Box Tee').first()).toBeVisible()
  await page.reload()
  await expect(page.getByText('Heavyweight Box Tee').first()).toBeVisible()
  await page.getByPlaceholder('Discount code').fill('WELCOME10')
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(page.getByText(/WELCOME10 applied/)).toBeVisible()
  await page.getByRole('button', { name: 'Continue to checkout' }).click()
  await expect(page.getByRole('heading', { name: 'Almost yours.' })).toBeVisible()
})

test('simulated failure retains the bag and gives a retry path', async ({ page }) => {
  await page.goto('/products/heavyweight-box-tee')
  await page.locator('.sizes').getByRole('button', { name: 'M' }).click()
  await page.getByRole('button', { name: /Add to bag/ }).click()
  await page.goto('/checkout')
  await page.getByLabel('Full name').fill('Demo Customer')
  await page.getByLabel('Email address').fill('demo@example.com')
  await page.getByLabel('Mobile number').fill('9876543210')
  await page.getByLabel('Address', { exact: true }).fill('10 Demo Street')
  await page.getByLabel('City').fill('Mumbai')
  await page.getByLabel('State').fill('Maharashtra')
  await page.getByLabel('PIN code').fill('400001')
  await page.getByRole('button', { name: /Continue to simulated payment/ }).click()
  await page.getByRole('button', { name: 'Simulate failure' }).click()
  await expect(page.getByText('The simulated payment failed. Your bag is unchanged.')).toBeVisible()
  await page.getByRole('button', { name: 'Return to your bag' }).click()
  await expect(page.getByText('Heavyweight Box Tee').first()).toBeVisible()
})

